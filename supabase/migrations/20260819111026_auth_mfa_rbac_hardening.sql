-- Preparacao local da transicao para Supabase Auth + MFA + RBAC.
--
-- Esta migration e deliberadamente aditiva e nao cria usuarios, clinicas ou
-- memberships. O bootstrap das duas contas owner deve ser uma operacao
-- posterior, autenticada e auditada. Ela tambem nao altera as tabelas clinicas
-- legadas, que continuam acessiveis somente pelo service_role/Edge Functions.

create schema if not exists private;

revoke all on schema private from public, anon, authenticated, service_role;

-- Captura no historico local as tres tabelas RBAC que ja existem no projeto
-- remoto. Os IF NOT EXISTS tornam a migration executavel tanto sobre o banco
-- atual quanto sobre um banco local reconstruido do zero.
create table if not exists public.clinics (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  city text,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);

create table if not exists public.clinic_members (
  clinic_id uuid not null references public.clinics(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null,
  status text not null default 'active',
  created_at timestamptz not null default now(),
  primary key (clinic_id, user_id)
);

