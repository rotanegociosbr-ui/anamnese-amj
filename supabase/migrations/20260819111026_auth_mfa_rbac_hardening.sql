-- Helpers RLS ficam em schema nao exposto, usam o usuario autenticado da
-- propria sessao e nao aceitam user_id fornecido pelo cliente.
create or replace function private.has_aal2()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $function$
  select coalesce((select auth.jwt() ->> 'aal') = 'aal2', false);
$function$;

create or replace function private.is_clinic_member(target_clinic uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select (select auth.uid()) is not null
    and exists (
      select 1
      from public.clinic_members as member
      where member.clinic_id = target_clinic
        and member.user_id = (select auth.uid())
        and member.status = 'active'
    );
$function$;

