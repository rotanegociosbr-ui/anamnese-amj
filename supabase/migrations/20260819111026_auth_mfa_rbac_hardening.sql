-- RPC exclusivamente server-side. A Edge Function primeiro valida o Bearer em
-- /auth/v1/user e depois confirma que o session_id do JWT ainda existe. Logout
-- remove a sessao; expiracao normal continua sendo verificada pelo JWT/Auth.
create or replace function public.clinic_validate_auth_session(
  p_user_id uuid,
  p_session_id uuid
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $function$
  select p_user_id is not null
    and p_session_id is not null
    and exists (
      select 1
      from auth.sessions as session
      where session.id = p_session_id
        and session.user_id = p_user_id
    );
$function$;

