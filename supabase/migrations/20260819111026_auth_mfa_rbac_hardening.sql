-- Nao permite remover ou suspender o ultimo owner ativo. O lock na clinica
-- serializa duas tentativas concorrentes de rebaixamento.
create or replace function private.protect_last_active_clinic_owner()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  remaining_owners integer;
begin
  if old.role = 'owner'
     and old.status = 'active'
     and (
       tg_op = 'DELETE'
       or new.role <> 'owner'
       or new.status <> 'active'
       or new.clinic_id <> old.clinic_id
     ) then
    perform 1
    from public.clinics
    where id = old.clinic_id
    for update;

    select count(*)
    into remaining_owners
    from public.clinic_members as member
    where member.clinic_id = old.clinic_id
      and member.role = 'owner'
      and member.status = 'active'
      and (member.clinic_id, member.user_id) <>
          (old.clinic_id, old.user_id);

    if remaining_owners = 0 then
      raise exception 'a clinica deve manter ao menos um owner ativo'
        using errcode = '23514';
    end if;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$function$;

revoke execute on function private.protect_last_active_clinic_owner()
  from public, anon, authenticated, service_role;

drop trigger if exists clinic_members_protect_last_owner
  on public.clinic_members;
create trigger clinic_members_protect_last_owner
before update or delete on public.clinic_members
for each row execute function private.protect_last_active_clinic_owner();

