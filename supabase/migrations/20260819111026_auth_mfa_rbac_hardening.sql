-- Remove as policies permissivas antigas (incluindo UPDATE sem WITH CHECK e
-- INSERT direto na auditoria) e recria um conjunto fechado e nominal.
do $migration$
declare
  old_policy record;
begin
  for old_policy in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in ('clinics', 'clinic_members', 'clinic_audit_log')
  loop
    execute format(
      'drop policy if exists %I on %I.%I',
      old_policy.policyname,
      old_policy.schemaname,
      old_policy.tablename
    );
  end loop;
end
$migration$;

