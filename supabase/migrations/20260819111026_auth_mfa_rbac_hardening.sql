-- Detalhes de auditoria aceitam somente metadados tecnicos pequenos e planos.
-- Nome, CPF, telefone, email, texto clinico, IP, token e payload nao pertencem
-- a esta coluna. Identificadores de recursos ficam nas colunas tipadas.
create or replace function private.audit_details_are_safe(p_details jsonb)
returns boolean
language sql
immutable
strict
parallel safe
set search_path = ''
as $function$
  select jsonb_typeof(p_details) = 'object'
    and pg_column_size(p_details) <= 4096
    and not exists (
      select 1
      from jsonb_each(p_details) as item(key, value)
      where item.key not in (
        'source',
        'mode',
        'route',
        'endpoint',
        'operation',
        'target_kind',
        'reason_code',
        'error_code',
        'http_status',
        'status_code',
        'item_count',
        'result_count',
        'duration_ms',
        'idempotent',
        'version',
        'previous_status',
        'new_status',
        'previous_role',
        'new_role',
        'legacy_event_id'
      )
      or jsonb_typeof(item.value) not in ('string', 'number', 'boolean', 'null')
      or (
        jsonb_typeof(item.value) = 'string'
        and (
          length(item.value #>> '{}') > 160
          or (item.value #>> '{}') !~ '^[A-Za-z0-9_.:/-]*$'
        )
      )
    );
$function$;

revoke execute on function private.audit_details_are_safe(jsonb)
  from public, anon, authenticated, service_role;
grant execute on function private.audit_details_are_safe(jsonb)
  to service_role;

